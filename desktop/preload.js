'use strict';
const { contextBridge, ipcRenderer } = require('electron');

// The renderer gets exactly these calls and nothing else.
contextBridge.exposeInMainWorld('tracker', {
  state: () => ipcRenderer.invoke('state'),
  login: (p) => ipcRenderer.invoke('login', p),
  findCompany: (email) => ipcRenderer.invoke('find-company', { email }),
  openForgot: (serverUrl) => ipcRenderer.invoke('open-forgot', { serverUrl }),
  logout: () => ipcRenderer.invoke('logout'),
  acceptPolicy: () => ipcRenderer.invoke('accept-policy'),
  projects: () => ipcRenderer.invoke('projects'),
  myTasks: () => ipcRenderer.invoke('my-tasks'),
  setTaskStatus: (id, status) => ipcRenderer.invoke('task-status', id, status),
  start: (projectId, taskId) => ipcRenderer.invoke('start', projectId, taskId),
  pause: (reason) => ipcRenderer.invoke('pause', reason),
  resume: () => ipcRenderer.invoke('resume'),
  stop: () => ipcRenderer.invoke('stop'),
  summary: (day) => ipcRenderer.invoke('summary', day),
  ackRecovered: () => ipcRenderer.invoke('ack-recovered'),
  requestPermission: () => ipcRenderer.invoke('request-permission'),
  testCapture: () => ipcRenderer.invoke('test-capture'),
  relaunch: () => ipcRenderer.invoke('relaunch'),
  openPermissionSettings: () => ipcRenderer.invoke('open-permission-settings'),
  prefs: () => ipcRenderer.invoke('prefs'),
  setOpenAtLogin: (on) => ipcRenderer.invoke('set-open-at-login', on),
  onPrefs: (cb) => ipcRenderer.on('prefs', (_e, p) => cb(p)),
  panelInfo: () => ipcRenderer.invoke('panel-info'),
  panelSize: (h) => ipcRenderer.invoke('panel-size', h),
  openMain: () => ipcRenderer.invoke('open-main'),
  openDashboard: () => ipcRenderer.invoke('open-dashboard'),
  quitApp: () => ipcRenderer.invoke('quit-app'),
  onPanelOpened: (cb) => ipcRenderer.on('panel-opened', () => cb()),
  updateState: () => ipcRenderer.invoke('update-state'),
  checkUpdate: () => ipcRenderer.invoke('update-check'),
  installUpdate: () => ipcRenderer.invoke('update-install'),
  revealUpdate: () => ipcRenderer.invoke('update-reveal'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, st) => cb(st)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, st) => cb(st)),
  onEvent: (cb) => ipcRenderer.on('event', (_e, ev) => cb(ev)),
  onConfirmStop: (cb) => ipcRenderer.on('confirm-stop', () => cb()),
  onTasksChanged: (cb) => ipcRenderer.on('tasks-changed', () => cb()),
  // the boost clip window, and each person's choice of how boosts arrive
  boostData: () => ipcRenderer.invoke('boost-data'),
  boostMouse: (over) => ipcRenderer.invoke('boost-mouse', over),
  boostAnswer: (id, answer) => ipcRenderer.invoke('boost-answer', id, answer),
  boostClose: () => ipcRenderer.invoke('boost-close'),
  boostPrefs: () => ipcRenderer.invoke('boost-prefs'),
  setBoostPrefs: (p) => ipcRenderer.invoke('set-boost-prefs', p),
});
